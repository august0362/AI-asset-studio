"""Kaggle job package: one self-contained kernel script + ``kernel-metadata.json``, and a private input dataset.

A Kaggle script kernel uploads only its ``code_file``, so ``runner.py``, ``entry.py`` and ``job.json`` (the same
package the mock runs, see :mod:`.packaging`) are embedded in the script and unpacked to ``/tmp/aas_pkg`` at start.
Outputs go to ``/kaggle/working/aas_output`` (downloaded by ``kaggle kernels output``). Inputs come from the job's
private dataset; the script finds its mount through a marker file, because the mount point under ``/kaggle/input``
is not guaranteed. Nothing here contains credentials (CONTRACTS §10).
"""

from __future__ import annotations

import base64
import json
import re
import shutil
from pathlib import Path

from ..client.base import KaggleGroupSpec, KaggleJobSpec
from .packaging import OUTPUT_DIR_NAME, RUNNER_SOURCE, build_group_document, build_job_document

KERNEL_FILE = "aas_kernel.py"
INPUT_MARKER = "aas_inputs.json"
KAGGLE_WORKING = "/kaggle/working"
KAGGLE_INPUT = "/kaggle/input"
TELEMETRY_INTERVAL_SECONDS = 15
SLUG_PREFIX = "aas-"

_WRAPPER = '''"""AI Asset Studio job {job_id}. Generated by kaggle_connector; contains no credentials."""
import base64
import json
import os
import sys
from pathlib import Path

FILES = {files}
INPUT_MARKER = {marker!r}
ROOT = Path("/")  # the notebook's filesystem root; tests run this script with another root

package = ROOT / "tmp" / "aas_pkg"
package.mkdir(parents=True, exist_ok=True)
for name, data in FILES.items():
    (package / name).write_bytes(base64.b64decode(data))
job = json.loads((package / "job.json").read_text(encoding="utf-8"))
kaggle_input = ROOT / "kaggle" / "input"
job["input_dir"] = str(kaggle_input / Path(job["input_dir"]).name)
job["output_dir"] = str(ROOT / "kaggle" / "working" / Path(job["output_dir"]).name)
if INPUT_MARKER and not (Path(job["input_dir"]) / INPUT_MARKER).is_file():
    for root, _dirs, names in os.walk(kaggle_input):
        if INPUT_MARKER in names:
            job["input_dir"] = root
            break
(package / "job.json").write_text(json.dumps(job), encoding="utf-8")
sys.path.insert(0, str(package))
import runner  # noqa: E402

code = runner.main(["runner", str(package / "job.json")])
if code != 0:
    # An uncaught exception makes Kaggle report the run as ERROR (a bare exit code may not).
    raise RuntimeError("AI Asset Studio job failed; see the ERROR line above.")
'''


# A run group (CONTRACTS §14.4): one kernel, both jobs. Each job with inputs has its own dataset; its mount is found
# through the marker file, which names the job.
_GROUP_WRAPPER = '''"""AI Asset Studio run group {group_id}. Generated by kaggle_connector; contains no credentials."""
import base64
import json
import os
import sys
from pathlib import Path

FILES = {files}
INPUT_MARKER = {marker!r}
ROOT = Path("/")  # the notebook's filesystem root; tests run this script with another root

package = ROOT / "tmp" / "aas_pkg"
package.mkdir(parents=True, exist_ok=True)
for name, data in FILES.items():
    (package / name).write_bytes(base64.b64decode(data))
doc = json.loads((package / "job.json").read_text(encoding="utf-8"))
kaggle_input = ROOT / "kaggle" / "input"
mounts = {{}}
for root, _dirs, names in os.walk(kaggle_input):
    if INPUT_MARKER in names:
        try:
            mounts[json.loads((Path(root) / INPUT_MARKER).read_text(encoding="utf-8"))["job_id"]] = root
        except (OSError, ValueError, KeyError):
            pass
for job in doc["jobs"]:
    job["input_dir"] = mounts.get(job["job_id"], str(kaggle_input / "none"))
doc["output_dir"] = str(ROOT / "kaggle" / "working" / Path(doc["output_dir"]).name)
(package / "job.json").write_text(json.dumps(doc), encoding="utf-8")
sys.path.insert(0, str(package))
import runner  # noqa: E402

code = runner.main(["runner", str(package / "job.json")])
if code != 0:
    # An uncaught exception makes Kaggle report the run as ERROR (a bare exit code may not).
    raise RuntimeError("AI Asset Studio run group failed: both jobs failed; see the ERROR lines above.")
'''


def slug_for(job_id: str, prefix: str = SLUG_PREFIX) -> str:
    """``job_20261106T101500Z_a1b2c3`` → ``aas-job-20261106t101500z-a1b2c3`` (Kaggle slugs: lower-case, dashes)."""
    slug = re.sub(r"[^a-z0-9]+", "-", job_id.lower()).strip("-")
    return (prefix + slug)[:50].rstrip("-")


def dataset_slug_for(job_id: str) -> str:
    return slug_for(job_id, prefix="aas-in-")


def kernel_source(spec: KaggleJobSpec, *, input_dir: str) -> str:
    document = build_job_document(
        spec,
        input_dir=input_dir,
        output_dir=f"{KAGGLE_WORKING}/{OUTPUT_DIR_NAME}",
        telemetry={"mode": "live", "interval_seconds": TELEMETRY_INTERVAL_SECONDS},
    )
    files = {
        "runner.py": RUNNER_SOURCE.read_bytes(),
        "entry.py": spec.entrypoint_file.read_bytes(),
        "job.json": json.dumps(document, indent=2).encode("utf-8"),
    }
    encoded = {name: base64.b64encode(data).decode("ascii") for name, data in files.items()}
    return _WRAPPER.format(
        job_id=spec.job_id,
        files=json.dumps(encoded, indent=1),
        marker=INPUT_MARKER if spec.requires_input_upload else "",
    )


def write_kernel_package(
    spec: KaggleJobSpec, folder: Path, *, owner: str, slug: str, dataset_ref: str | None, gpu: bool
) -> Path:
    """Writes ``aas_kernel.py`` and ``kernel-metadata.json``: private; internet only when the job needs it."""
    folder.mkdir(parents=True, exist_ok=True)
    input_dir = f"{KAGGLE_INPUT}/{dataset_ref.split('/', 1)[1]}" if dataset_ref else f"{KAGGLE_INPUT}/none"
    (folder / KERNEL_FILE).write_text(kernel_source(spec, input_dir=input_dir), encoding="utf-8")
    metadata = {
        "id": f"{owner}/{slug}",
        "title": slug,
        "code_file": KERNEL_FILE,
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": gpu,
        "enable_internet": spec.internet,
        "dataset_sources": [dataset_ref] if dataset_ref else [],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }
    (folder / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    return folder


def group_kernel_source(spec: KaggleGroupSpec) -> str:
    document = build_group_document(
        spec,
        input_dirs=[f"{KAGGLE_INPUT}/none"] * len(spec.members),  # resolved from the markers at start
        output_dir=f"{KAGGLE_WORKING}/{OUTPUT_DIR_NAME}",
        telemetry={"mode": "live", "interval_seconds": TELEMETRY_INTERVAL_SECONDS},
    )
    files = {
        "runner.py": RUNNER_SOURCE.read_bytes(),
        "job.json": json.dumps(document, indent=2).encode("utf-8"),
    }
    for index, member in enumerate(spec.members):
        files[f"entry_{index}.py"] = member.entrypoint_file.read_bytes()
    encoded = {name: base64.b64encode(data).decode("ascii") for name, data in files.items()}
    return _GROUP_WRAPPER.format(
        group_id=spec.group_id, files=json.dumps(encoded, indent=1), marker=INPUT_MARKER
    )


def write_group_kernel_package(
    spec: KaggleGroupSpec, folder: Path, *, owner: str, slug: str, dataset_refs: list[str], gpu: bool
) -> Path:
    """Like :func:`write_kernel_package`, for a run group: every member's input dataset is attached (D-042)."""
    folder.mkdir(parents=True, exist_ok=True)
    (folder / KERNEL_FILE).write_text(group_kernel_source(spec), encoding="utf-8")
    metadata = {
        "id": f"{owner}/{slug}",
        "title": slug,
        "code_file": KERNEL_FILE,
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": gpu,
        "enable_internet": spec.internet,
        "dataset_sources": list(dataset_refs),
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }
    (folder / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    return folder


def write_dataset_package(spec: KaggleJobSpec, folder: Path, *, owner: str, slug: str) -> Path:
    """The job's inputs plus a marker, with ``dataset-metadata.json`` (private by default: no ``--public``)."""
    folder.mkdir(parents=True, exist_ok=True)
    names = []
    for path in spec.input_files:
        shutil.copyfile(path, folder / path.name)
        names.append(path.name)
    (folder / INPUT_MARKER).write_text(json.dumps({"job_id": spec.job_id, "files": names}), encoding="utf-8")
    metadata = {"title": slug, "id": f"{owner}/{slug}", "licenses": [{"name": "CC0-1.0"}]}
    (folder / "dataset-metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    return folder
